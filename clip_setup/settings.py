def get_dataset_config(name: str) -> DatasetConfig:
    try:
        return DATASETS[name]
    except KeyError as exc:
        raise KeyError(f"Unknown dataset '{name}'. Available datasets: {', '.join(sorted(DATASETS))}") from exc


def get_model_config(name: str) -> ModelConfig:
    try:
        return MODELS[name]
    except KeyError as exc:
        raise KeyError(f"Unknown model '{name}'. Available models: {', '.join(sorted(MODELS))}") from exc


def available_dataset_names() -> list[str]:
    return sorted(DATASETS)


def available_model_names() -> list[str]:
    return sorted(MODELS)
