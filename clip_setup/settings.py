from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

DEFAULT_NUM_REPHRASES = 30
DEFAULT_OUTPUT_DIR = Path("data")


def default_display_name(class_name: str) -> str:
    return class_name.replace("_", " ")


@dataclass(frozen=True)
class DatasetConfig:
    name: str
    hf_name: str
    split: str
    image_field: str
    label_field: str
    class_names: tuple[str, ...]
    prompt_template: str

    @property
    def num_classes(self) -> int:
        return len(self.class_names)

    def display_name(self, class_name: str) -> str:
        return default_display_name(class_name)

    def base_prompt(self, class_name: str) -> str:
        return self.prompt_template.format(label=self.display_name(class_name))

    def default_rephrased_path(self, output_dir: Path | str = DEFAULT_OUTPUT_DIR) -> Path:
        return Path(output_dir) / f"label_rephrased_dict_{self.name}.json"


@dataclass(frozen=True)
class ModelConfig:
    name: str
    family: str
    model_name: str
    processor_name: str | None = None
    pretrained: str | None = None
    probability_mode: str = "softmax"
    attn_implementation: str | None = None

    def output_prefix(self, dataset_name: str, output_dir: Path | str = DEFAULT_OUTPUT_DIR) -> Path:
        return Path(output_dir) / f"{self.name}_{dataset_name}"


